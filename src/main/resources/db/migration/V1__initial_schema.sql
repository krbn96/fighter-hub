-- FIGHTER HUB 初期スキーマ。
--
-- 既存のローカル開発DB(ddl-auto=updateで数ヶ月運用)に対して pg_dump --schema-only で取得した
-- 実スキーマと、各Entityの定義を照合して作成した。カラムの型・長さ・NOT NULL・DEFAULTの有無は
-- 実スキーマを正とした(推測で補わない)。制約名・インデックス名はHibernateの自動生成名
-- (ハッシュ値)を引き継がず、意味の分かる名前へ付け直している
-- (Hibernateのddl-auto=validateは制約名・インデックス名までは検証しないため、
--  名前を変えてもvalidateとは衝突しない)。
--
-- delete_flagにDB側のDEFAULTを付けていないのは、CLAUDE.mdの既存方針
-- 「DB DEFAULT FALSEには依存せず、Java Entity側で初期値falseを設定する」に合わせたもの
-- (実スキーマ上も delete_flag は NOT NULL のみでDEFAULTを持たない)。
--
-- FK列(tournament_id/owner_id/team_id/user_id等)へのインデックスは、実スキーマには
-- 存在しなかったが、Repositoryの検索・JOIN条件で頻繁に使われるため本マイグレーションで
-- 新規に追加している(末尾のCREATE INDEX群)。

CREATE TABLE m_characters (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE t_users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    character_1      BIGINT,
    rank_1           VARCHAR(30),
    mr_1             INTEGER,
    character_2      BIGINT,
    rank_2           VARCHAR(30),
    mr_2             INTEGER,
    character_3      BIGINT,
    rank_3           VARCHAR(30),
    mr_3             INTEGER,
    character_4      BIGINT,
    rank_4           VARCHAR(30),
    mr_4             INTEGER,
    play_time_start  TIME(0),
    play_time_end    TIME(0),
    message          TEXT,
    email            VARCHAR(255),
    x_id             VARCHAR(255),
    discord_id       VARCHAR(255),
    discord_username VARCHAR(255),
    password_hash    VARCHAR(255),
    role             VARCHAR(20) NOT NULL DEFAULT 'USER',
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    delete_flag      BOOLEAN NOT NULL,
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_discord_id UNIQUE (discord_id),
    CONSTRAINT fk_users_character_1 FOREIGN KEY (character_1) REFERENCES m_characters (id),
    CONSTRAINT fk_users_character_2 FOREIGN KEY (character_2) REFERENCES m_characters (id),
    CONSTRAINT fk_users_character_3 FOREIGN KEY (character_3) REFERENCES m_characters (id),
    CONSTRAINT fk_users_character_4 FOREIGN KEY (character_4) REFERENCES m_characters (id)
);

CREATE TABLE t_tournaments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(255) NOT NULL,
    team_size            INTEGER NOT NULL,
    start_at             TIMESTAMP(6) NOT NULL,
    recruitment_deadline TIMESTAMP(6) NOT NULL,
    max_players          INTEGER NOT NULL,
    created_at           TIMESTAMP(6) NOT NULL,
    updated_at           TIMESTAMP(6) NOT NULL,
    delete_flag          BOOLEAN NOT NULL
);

CREATE TABLE t_teams (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id          BIGINT NOT NULL,
    owner_id               BIGINT NOT NULL,
    name                   VARCHAR(255) NOT NULL,
    rank_requirement       VARCHAR(30),
    character_requirements JSONB,
    recruitment_message    TEXT,
    created_at             TIMESTAMP(6) NOT NULL,
    updated_at             TIMESTAMP(6) NOT NULL,
    delete_flag            BOOLEAN NOT NULL,
    CONSTRAINT fk_teams_tournament_id FOREIGN KEY (tournament_id) REFERENCES t_tournaments (id),
    CONSTRAINT fk_teams_owner_id FOREIGN KEY (owner_id) REFERENCES t_users (id)
);

CREATE TABLE t_team_members (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id   BIGINT NOT NULL,
    user_id   BIGINT NOT NULL,
    joined_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_team_members_team_id_user_id UNIQUE (team_id, user_id),
    CONSTRAINT fk_team_members_team_id FOREIGN KEY (team_id) REFERENCES t_teams (id),
    CONSTRAINT fk_team_members_user_id FOREIGN KEY (user_id) REFERENCES t_users (id)
);

CREATE TABLE t_recruitment_application (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id    BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    message    TEXT,
    status     VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_recruitment_application_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT fk_recruitment_application_team_id FOREIGN KEY (team_id) REFERENCES t_teams (id),
    CONSTRAINT fk_recruitment_application_user_id FOREIGN KEY (user_id) REFERENCES t_users (id)
);

-- 既存スキーマには存在しなかった、Repositoryの検索・JOIN条件で頻繁に使われるFK列へのインデックス。
CREATE INDEX idx_teams_tournament_id ON t_teams (tournament_id);
CREATE INDEX idx_teams_owner_id ON t_teams (owner_id);
CREATE INDEX idx_team_members_team_id ON t_team_members (team_id);
CREATE INDEX idx_team_members_user_id ON t_team_members (user_id);
CREATE INDEX idx_recruitment_application_team_id ON t_recruitment_application (team_id);
CREATE INDEX idx_recruitment_application_user_id ON t_recruitment_application (user_id);
